SET PAGESIZE 2000

SELECT
    UTBILDNINGSOMRÅDE,
    COUNT(*) AS ANTAL_ANSÖKNINGAR,
    COUNT(CASE WHEN BESLUT = 'Beviljad' THEN 1 END) AS ANTAL_BEVILJADE,
-- Andel beviljade ansökningar
    ROUND(COUNT(CASE WHEN BESLUT = 'Beviljad' THEN 1 END) / COUNT(*) * 100, 1) || ' %' AS ANDEL_BEVILJADE,
-- Andel beviljade distansutbildningar    
    ROUND(COUNT(CASE WHEN STUDIEFORM = 'Distans' THEN 1 END) / COUNT(*) * 100, 1) || ' %' AS BEVILJADE_DISTANS,
-- Andel beviljade bundna utbildningar
    ROUND(COUNT(CASE WHEN STUDIEFORM = 'Bunden' THEN 1 END) / COUNT(*) * 100, 1) || ' %' AS BEVILJADE_BUNDNA
FROM 
    ao_2025 
GROUP BY
    UTBILDNINGSOMRÅDE
ORDER BY
     ANDEL_BEVILJADE DESC;

EXIT
