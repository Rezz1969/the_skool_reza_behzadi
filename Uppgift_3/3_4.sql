SELECT
    UTBILDNINGSOMRÅDE,
    LÄN,
    COUNT(*) AS ANTAL_ANSÖKNINGAR,
    COUNT(CASE WHEN BESLUT = 'Beviljad' THEN 1 END) AS ANTAL_BEVILJADE,
    (ROUND(COUNT(CASE WHEN BESLUT = 'Beviljad' THEN 1 END) / COUNT(*) * 100, 1)) || ' %' AS ANDEL_BEVILJADE,
    (ROUND(COUNT(CASE WHEN STUDIEFORM = 'Distans' AND BESLUT = 'Beviljad' THEN 1 END) / COUNT(*) * 100, 1)) || ' %' AS BEVILJADE_DISTANS,
    (ROUND(COUNT(CASE WHEN STUDIEFORM = 'Bunden' AND BESLUT = 'Beviljad' THEN 1 END) / COUNT(*) * 100, 1)) || ' %' AS BEVILJADE_BUNDNA
FROM 
    ao_2025
WHERE 
    LÄN != 'Flera kommuner'
GROUP BY
    UTBILDNINGSOMRÅDE,
    LÄN
ORDER BY
    5 DESC
